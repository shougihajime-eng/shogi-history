/* ===================== 便利な関数 ===================== */

/** 配列をランダムに並べかえた新しい配列を返す（もとは変えない） */
export function shuffle<T>(arr: readonly T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** 難易度でしぼった問題を返す（"all" ならぜんぶ） */
export function questionsByLevel(level: Level | "all"): QuizQuestion[] {
  if (level === "all") return QUESTIONS;
  return QUESTIONS.filter((q) => q.level === level);
}

/** 1問ぶんの「表示用データ」。選択肢をシャッフルし、正解の位置も入れておく */
export interface PreparedQuestion {
  id: string;
  level: Level;
  q: string;
  /** シャッフル後の選択肢 */
  choices: string[];
  /** シャッフル後に正解が何番目か */
  answerIndex: number;
  explain: string;
}

/** 問題を「表示用データ」に整える（選択肢をシャッフル） */
export function prepare(q: QuizQuestion): PreparedQuestion {
  // choices[0] が正解。並びをシャッフルして、正解の新しい位置を覚えておく。
  const indexed = q.choices.map((text, i) => ({ text, correct: i === 0 }));
  const mixed = shuffle(indexed);
  return {
    id: q.id,
    level: q.level,
    q: q.q,
    choices: mixed.map((c) => c.text),
    answerIndex: mixed.findIndex((c) => c.correct),
    explain: q.explain,
  };
}

/** 難易度としぼり込み＋出題数を受け取り、シャッフル済みの表示用問題を返す */
export function buildQuiz(
  level: Level | "all",
  count?: number
): PreparedQuestion[] {
  const pool = shuffle(questionsByLevel(level)).map(prepare);
  if (count && count > 0) return pool.slice(0, count);
  return pool;
}
