/** 時代ごとに出来事をまとめて返す（並び順つき） */
export function eventsByEra(): { era: Era; events: ShogiEvent[] }[] {
  return ERAS.map((era) => ({
    era,
    events: EVENTS.filter((e) => e.era === era.id).sort(
      (a, b) => a.order - b.order
    ),
  }));
}

/** 昔から今までの順に並んだ全出来事 */
export function sortedEvents(): ShogiEvent[] {
  return [...EVENTS].sort((a, b) => a.order - b.order);
}
