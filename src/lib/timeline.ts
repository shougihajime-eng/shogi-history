// すべての年代・出来事はやさしい言葉で。出典（どこで確かめたか）も添える。

export type EraId =
  | "birth" // 誕生（インドで生まれる）
  | "arrival" // 日本へ（海をこえて）
  | "form" // 今の形へ（持ち駒の発明）
  | "edo" // 江戸（武士のたしなみ）
  | "modern" // 近代（連盟のはじまり）
  | "present"; // 現代（いまの将棋）

export interface Era {
  id: EraId;
  /** 章のタイトル（短い） */
  label: string;
  /** ふりがな */
  reading: string;
  /** 章のひとこと説明 */
  sub: string;
  /** この章をあらわす駒の文字 */
  koma: string;
}

export interface ShogiEvent {
  id: string;
  era: EraId;
  /** 画面に出す年代の表記 */
  year: string;
  /** 並び順（小さいほど昔） */
  order: number;
  /** 見出し */
  title: string;
  title_reading?: string;
  /** やさしい本文 */
  body: string;
  /** 出典（どこで確かめたか） */
  source?: string;
  /** 特別な出来事は true（金色で強調） */
  highlight?: boolean;
  /** 駒のノードに入れる一文字 */
  koma?: string;
}

